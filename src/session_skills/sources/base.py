"""Shared types and text-cleaning helpers for the session-source adapters.

Adapters yield *raw* sessions. Nothing an adapter returns is stored or sent anywhere until the
pipeline has passed it through :func:`session_skills.redact.redact`.
"""

from __future__ import annotations

import hashlib
import re
from collections.abc import Iterator
from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Literal, Protocol

Role = Literal["user", "assistant"]

ASSISTANT_CHARS = 600

# Marker placed at the top of every prompt this tool sends to a worker model. Worker CLIs write
# their own session files, so any session whose first human message carries the marker is ours
# and is skipped on the next build-list.
TOOL_MARKER = "[session-skills:worker-request]"

# Blocks injected into "user" turns by harnesses rather than typed by a person.
_INJECTED_BLOCKS = re.compile(
    r"<(system-reminder|task-notification|local-command-stdout|local-command-stderr|"
    r"local-command-caveat|bash-input|bash-stdout|bash-stderr|user-prompt-submit-hook|"
    r"environment_context|user_instructions|turn_aborted|agent-handoff|subagent-result|"
    r"command-message|command-name|command-contents)\b[^>]*>.*?</\1>",
    re.DOTALL | re.IGNORECASE,
)
_COMMAND_ARGS = re.compile(r"<command-args>(.*?)</command-args>", re.DOTALL)
_INJECTED_PREFIXES = (
    "Caveat: The messages below were generated by the user while running local commands",
    "This session is being continued from a previous conversation",
    "[Request interrupted by user",
    "# AGENTS.md instructions for",
    "<environment_context>",
    "<user_instructions>",
    "Base directory for this skill:",
)


@dataclass
class Message:
    role: Role
    text: str
    timestamp: str = ""


@dataclass
class Session:
    """One chat. ``key`` is a stable, private identifier that is only ever stored hashed: the
    agent's own session id when the format has one (so moving or archiving the file does not
    create a second chat), otherwise the file path."""

    source: str
    key: str
    fingerprint: str
    messages: list[Message] = field(default_factory=list)
    started: str = ""  # ISO date (YYYY-MM-DD) of the first message, "" if unknown

    @property
    def human_messages(self) -> list[Message]:
        return [m for m in self.messages if m.role == "user"]


class Adapter(Protocol):
    name: str
    warnings: list[str]  # problems reading sources (reported, never silently dropped)

    def iter_sessions(self) -> Iterator[Session]: ...


def clean_human_text(text: str) -> str:
    """Strip harness-injected blocks from a user turn; return "" if nothing human remains.

    Slash-command invocations keep only their typed arguments; the command's expanded prompt is
    injected as a separate turn which adapters drop.
    """
    if not text:
        return ""
    args = " ".join(a.strip() for a in _COMMAND_ARGS.findall(text) if a.strip())
    stripped = _COMMAND_ARGS.sub("", text)
    stripped = _INJECTED_BLOCKS.sub("", stripped).strip()
    if args and not stripped:
        stripped = args
    if not stripped:
        return ""
    for prefix in _INJECTED_PREFIXES:
        if stripped.startswith(prefix):
            return ""
    return stripped


def clip_assistant(text: str) -> str:
    text = _INJECTED_BLOCKS.sub("", text or "").strip()
    return text[:ASSISTANT_CHARS]


def iso_date(value: object) -> str:
    """Best-effort conversion of an ISO string or epoch (s or ms) to YYYY-MM-DD."""
    if isinstance(value, bool) or value is None:
        return ""
    if isinstance(value, (int, float)):
        seconds = value / 1000 if value > 10_000_000_000 else value
        try:
            return datetime.fromtimestamp(seconds, UTC).date().isoformat()
        except (OverflowError, OSError, ValueError):
            return ""
    if isinstance(value, str) and value:
        try:
            return datetime.fromisoformat(value).date().isoformat()
        except ValueError:
            return value[:10] if re.match(r"\d{4}-\d{2}-\d{2}", value) else ""
    return ""


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def is_tool_session(messages: list[Message]) -> bool:
    first = next((m for m in messages if m.role == "user"), None)
    return first is not None and TOOL_MARKER in first.text


def finish(session: Session) -> Session | None:
    """Drop sessions with no human-typed text or that were created by this tool's own workers."""
    if not session.human_messages or is_tool_session(session.messages):
        return None
    if not session.started:
        for message in session.messages:
            if message.timestamp:
                session.started = iso_date(message.timestamp)
                if session.started:
                    break
    return session
